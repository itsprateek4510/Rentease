export function storedLocation() {
  try {
    const value = JSON.parse(localStorage.getItem('location'));
    if (value && value.country === 'IN' && typeof value.city === 'string') return value;
  } catch { /* older sessions only stored a city */ }
  return { city: (localStorage.getItem('city') || '').trim().toLowerCase(), country: 'IN' };
}
